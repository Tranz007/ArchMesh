const nodes = [];
const edges = [];

for (let index = 0; index < 26; index += 1) {
  nodes.push({
    id: `file:area-${index}.ts`,
    label: `Area ${index}`,
    kind: 'service',
    path: `features/area-${index}/service.ts`,
    health: 'healthy',
    change: 'unchanged',
  });
}

for (let index = 0; index < 12; index += 1) {
  nodes.push({
    id: `integration:provider-${index}`,
    label: `Provider ${index}`,
    kind: 'integration',
    health: 'healthy',
    change: 'unchanged',
  });
}

let edgeNumber = 1;
for (const [source, target] of featureEdges) {
  edges.push({
    id: `edge:${edgeNumber++}`,
    source: `file:area-${source}.ts`,
    target: `file:area-${target}.ts`,
    relation: 'imports',
    health: 'healthy',
    change: 'unchanged',
  });
}

for (const [source, target, flowDirection] of integrationEdges) {
  edges.push({
    id: `edge:${edgeNumber++}`,
    source: `file:area-${source}.ts`,
    target: `integration:provider-${target}`,
    relation: 'integrates-with',
    health: 'healthy',
    change: 'unchanged',
    ...(flowDirection ? { metadata: { flowDirection } } : {}),
  });
}

const graph = {
  project: 'System Overview Fixture',
  generatedAt: new Date().toISOString(),
  nodes,
  edges,
  metadata: { fixture: 'system-overview-39-dense' },
};

await fs.mkdir('public', { recursive: true });
await fs.writeFile('public/archmesh.json', `${JSON.stringify(graph, null, 2)}\n`);
await fs.writeFile('public/archmesh-drift.json', `${JSON.stringify({ ...graph, nodes: [], edges: [], metadata: { graphKind: 'drift' } }, null, 2)}\n`);
